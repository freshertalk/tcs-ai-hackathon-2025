// scripts/prerender.js
// ---------------------------------------------------------------------------
// Turns the CRA single-page bundle into real, crawlable HTML documents.
//
// Why this exists
// ---------------
// `npm run build` ships <div id="root"></div> and nothing else. Googlebot will
// eventually render that, but it is a second-pass, best-effort job — and the
// answer engines this site is trying to reach (GPTBot, ClaudeBot,
// PerplexityBot, OAI-SearchBot, CCBot) generally do NOT execute JavaScript at
// all. To them an unrendered SPA is a blank page.
//
// So after the build we render each route to static HTML with the same React
// tree the browser uses, inject it into build/index.html, and write:
//
//   build/index.html                       →  /
//   build/library/index.html               →  /library
//   build/books/<slug>/index.html          →  /books/<slug>   (one per book)
//
// The library catalogue and each book's metadata are inlined as
// window.__LIBRARY__, so the first paint in a browser already has them. The
// reader (/read/…) is not prerendered: it is an app, and it is noindex.
//
// It also writes build/sitemap.xml from the catalogue (so a newly published
// book is listed automatically) and removes the public/ebooks drop box,
// which is a source location, not something to serve.
//
// This step is deliberately fail-soft: if anything goes wrong it warns and
// leaves the normal SPA build in place rather than breaking a deploy.
// ---------------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const Module = require("module");

const ROOT = path.resolve(__dirname, "..");
const BUILD = path.join(ROOT, "build");
const SRC = path.join(ROOT, "src");

const ORIGIN = "https://vinaytiwari.org";
const CONTENT = path.join(ROOT, "public", "content");

/** The catalogue and every book's metadata, straight from the published files. */
function loadLibrary() {
  const lib = { catalog: { books: [] }, books: {} };
  const indexPath = path.join(CONTENT, "index.json");
  if (!fs.existsSync(indexPath)) return lib;

  lib.catalog = JSON.parse(fs.readFileSync(indexPath, "utf8"));
  for (const b of lib.catalog.books) {
    const bookPath = path.join(CONTENT, b.slug, "book.json");
    if (fs.existsSync(bookPath)) lib.books[b.slug] = JSON.parse(fs.readFileSync(bookPath, "utf8"));
  }
  return lib;
}

function routesFor(lib) {
  return [
    { url: "/", out: "index.html", lang: "hi", seed: true },
    { url: "/library", out: path.join("library", "index.html"), lang: "hi", seed: true },
    ...lib.catalog.books.map((b) => ({
      url: `/books/${b.slug}`,
      out: path.join("books", b.slug, "index.html"),
      lang: "hi",
      seed: true,
      slug: b.slug,
    })),
  ];
}

/** JSON that is safe inside an inline <script> (no premature </script>). */
const BACKSLASH = String.fromCharCode(92);
const inlineJson = (v) =>
  JSON.stringify(v)
    .replace(/</g, BACKSLASH + "u003c")
    .replace(/\u2028/g, BACKSLASH + "u2028")
    .replace(/\u2029/g, BACKSLASH + "u2029");

function sitemapXml(lib) {
  const day = (iso) => String(iso || "").slice(0, 10) || new Date().toISOString().slice(0, 10);
  const books = lib.catalog.books;
  const newest =
    books
      .map((b) => day(b.updated))
      .sort()
      .pop() || day();

  const entry = (loc, lastmod, freq, prio, image) => {
    const img = image
      ? `
    <image:image>
      <image:loc>${ORIGIN}${image.loc}</image:loc>
      <image:title>${image.title}</image:title>
    </image:image>`
      : "";
    return `  <url>
    <loc>${ORIGIN}${loc}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${freq}</changefreq>
    <priority>${prio}</priority>${img}
  </url>`;
  };

  const urls = [
    entry("/", newest, "monthly", "1.0", {
      loc: "/og-image.jpg",
      title: "दो कुल्हड़ चाय — विनय कुमार तिवारी का पहला हिन्दी उपन्यास",
    }),
    entry("/library", newest, "monthly", "0.8"),
    ...books.map((b) =>
      entry(
        `/books/${b.slug}`,
        day(b.updated),
        "monthly",
        "0.9",
        b.cover ? { loc: `/content/${b.slug}/${b.cover}`, title: `${b.title} — आवरण` } : null
      )
    ),
  ];

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/prerender.js from public/content/index.json -->
<urlset
  xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
  xmlns:image="http://www.google.com/schemas/sitemap-image/1.1"
>
${urls.join("\n\n")}
</urlset>
`;
}

/* ------------------------------------------------ compile src/ for node */
function installRequireHooks() {
  const { transform } = require("sucrase");
  const compileJs = Module._extensions[".js"];

  const tx = (mod, filename) => {
    const { code } = transform(fs.readFileSync(filename, "utf8"), {
      transforms: ["jsx", "imports"],
      jsxRuntime: "automatic",
      production: true,
      filePath: filename,
    });
    mod._compile(code, filename);
  };

  Module._extensions[".js"] = (m, f) => (f.startsWith(SRC) ? tx(m, f) : compileJs(m, f));
  Module._extensions[".jsx"] = tx;
  Module._extensions[".css"] = (m, f) => m._compile("module.exports={};", f);
  for (const ext of [".png", ".jpg", ".jpeg", ".svg", ".webp", ".avif", ".ico", ".gif"]) {
    Module._extensions[ext] = (m, f) => m._compile('module.exports="";', f);
  }
}

/* ------------------------------------------------------------- helpers */

// React 19 hoists <title>/<meta>/<link>/<script ld+json> to the front of the
// renderToString output. Peel those off so they can go in <head> where they
// belong, and keep the rest as the body markup.
function splitHeadAndBody(html) {
  const HEAD_TAG =
    /^\s*(?:<title>[\s\S]*?<\/title>|<meta\b[^>]*\/?>|<link\b[^>]*\/?>|<script type="application\/ld\+json"[^>]*>[\s\S]*?<\/script>)/;
  let head = "";
  let rest = html;
  for (;;) {
    const m = rest.match(HEAD_TAG);
    if (!m) break;
    head += m[0].trim();
    rest = rest.slice(m[0].length);
  }
  return { head, body: rest };
}

// Remove tags the rendered head will supply, so nothing is duplicated.
function stripConflicting(template) {
  return template
    .replace(/<title>[\s\S]*?<\/title>\s*/i, "")
    .replace(/<meta\s+name="(description|keywords|robots|author)"[^>]*>\s*/gi, "")
    .replace(/<meta\s+(?:property|name)="(?:og|twitter|profile):[^"]*"[^>]*>\s*/gi, "")
    .replace(/<link\s+rel="canonical"[^>]*>\s*/gi, "")
    .replace(/<link\s+rel="alternate"\s+hreflang[^>]*>\s*/gi, "")
    .replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\s*/gi, "");
}

/* ---------------------------------------------------------------- main */
function main() {
  const templatePath = path.join(BUILD, "index.html");
  if (!fs.existsSync(templatePath)) {
    console.warn("[prerender] build/index.html not found — run `npm run build` first. Skipping.");
    return;
  }

  installRequireHooks();
  process.env.NODE_ENV = "production";
  process.env.PUBLIC_URL = process.env.PUBLIC_URL || "";

  const React = require("react");
  const { renderToString } = require("react-dom/server");
  const { StaticRouter } = require("react-router-dom");
  const App = require(path.join(SRC, "App.js")).default;

  const lib = loadLibrary();
  globalThis.__LIBRARY__ = lib; // the same seed the browser gets, for the render below
  const ROUTES = routesFor(lib);

  const rawTemplate = fs.readFileSync(templatePath, "utf8");
  const template = stripConflicting(rawTemplate);

  if (!template.includes('<div id="root"></div>')) {
    console.warn('[prerender] could not find <div id="root"></div> — skipping.');
    return;
  }

  let ok = 0;
  for (const route of ROUTES) {
    try {
      const rendered = renderToString(
        React.createElement(
          StaticRouter,
          { location: route.url },
          React.createElement(App)
        )
      );
      const { head, body } = splitHeadAndBody(rendered);

      // the library must be in the page before the bundle runs
      let seed = "";
      if (route.seed) {
        const data = {
          catalog: lib.catalog,
          books: route.slug ? { [route.slug]: lib.books[route.slug] } : {},
        };
        seed = `<script>window.__LIBRARY__=${inlineJson(data)}</script>`;
      }

      const html = template
        // React cannot hoist <html lang>, so it is written per route here
        .replace(/<html([^>]*)\slang="[^"]*"/i, `<html$1 lang="${route.lang}"`)
        .replace("</head>", () => `${head}${seed}\n  </head>`)
        .replace('<div id="root"></div>', `<div id="root">${body}</div>`);

      const outPath = path.join(BUILD, route.out);
      fs.mkdirSync(path.dirname(outPath), { recursive: true });
      fs.writeFileSync(outPath, html, "utf8");

      const kb = (Buffer.byteLength(html) / 1024).toFixed(1);
      console.log(`[prerender] ${route.url.padEnd(11)} → ${route.out.padEnd(22)} ${kb} KB`);
      ok++;
    } catch (err) {
      console.warn(`[prerender] ${route.url} failed: ${err.message}`);
    }
  }
  console.log(`[prerender] ${ok}/${ROUTES.length} routes written as static HTML`);

  // The reader is an app, not a document: /read/* is served this neutral
  // shell (see _redirects / .htaccess) instead of the home page's HTML, so a
  // chapter never inherits the home page's canonical or robots tags next to
  // its own.
  try {
    const shell = template
      .replace(/<html([^>]*)\slang="[^"]*"/i, `<html$1 lang="hi"`)
      .replace(
        "</head>",
        () =>
          `<title>दो कुल्हड़ चाय — पढ़िए</title>\n    <meta name="robots" content="noindex, follow" />\n  </head>`
      );
    fs.mkdirSync(path.join(BUILD, "read"), { recursive: true });
    fs.writeFileSync(path.join(BUILD, "read", "index.html"), shell, "utf8");
    console.log("[prerender] /read/*   → read\\index.html (reader shell)");
  } catch (err) {
    console.warn(`[prerender] reader shell failed: ${err.message}`);
  }

  // sitemap, from the catalogue
  fs.writeFileSync(path.join(BUILD, "sitemap.xml"), sitemapXml(lib), "utf8");
  console.log(`[prerender] sitemap.xml written (${ROUTES.length} URLs)`);

  // the drop box is a source location; the served copy lives in /content
  fs.rmSync(path.join(BUILD, "ebooks"), { recursive: true, force: true });
}

try {
  main();
} catch (err) {
  console.warn("[prerender] skipped:", err.message);
}
